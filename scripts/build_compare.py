#!/usr/bin/env python3
"""Build the comparison pages under compare/ from content/compare/*.json.

    python3 -B scripts/build_compare.py          # write compare/<slug>/index.html
    python3 -B scripts/build_compare.py --check  # fail if any generated page is stale

Every page follows COMPARE-SPEC.md: a short answer, an at-a-glance table, a
feature table, the sections the spec names, a verdict, at least six FAQs (shown
on the page and repeated in FAQPage JSON-LD from the same source), sources and
at least eight related internal links. `scripts/seo.py check` enforces the spec
on every page under compare/, including the hand-written ones.

Content strings may contain inline HTML. Links that start with "/" are site
links and are rewritten relative to the page. [[text]] marks another company's
fact (a price, a macOS version) so the price check in seo.py ignores it.
Standard library only.
"""
import argparse
from datetime import date
from html import escape
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content" / "compare"
SITE = "https://macex.app"
CSS_VERSION = {"style": "20261126", "docs": "20261118", "article": "20261120"}
TAGS = {"yes": "Yes", "no": "No", "part": "Partly"}
GENERATED = "<!-- Generated by scripts/build_compare.py from content/compare/{slug}.json. Edit the JSON, not this file. -->"


def tp(text):
    """[[x]] -> a span the seo.py price and version check skips (another product's fact)."""
    return re.sub(r"\[\[(.+?)\]\]", r"<span data-third-party>\1</span>", text)


def plain(text):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", re.sub(r"\[\[(.+?)\]\]", r"\1", text))).strip()


def fmt_date(iso):
    d = date.fromisoformat(iso)
    return f"{d.strftime('%B')} {d.day}, {d.year}"


class Page:
    def __init__(self, data):
        self.d = data
        self.slug = data["slug"]
        self.path = "/compare/" if self.slug == "index" else f"/compare/{self.slug}/"
        self.url = SITE + self.path
        self.prefix = "../" * self.path.strip("/").count("/") + "../"

    def rel(self, html):
        """Rewrite href="/x/" to a path relative to this page, as the hand-written pages do."""
        def swap(match):
            target = match.group(2)
            if target.startswith("//"):
                return match.group(0)
            return f'{match.group(1)}="{self.prefix}{target.lstrip("/")}"'
        return re.sub(r'(href|src)="(/[^"]*)"', swap, html)

    def html(self, text):
        return self.rel(tp(text))

    # ---- head -------------------------------------------------------------
    def jsonld(self):
        d = self.d
        crumbs = [("MacEx", SITE + "/")]
        if self.slug != "index":
            crumbs.append(("Compare", SITE + "/compare/"))
        crumbs.append((d["crumb"], self.url))
        graph = [{
            "@type": "Article" if self.slug != "index" else "CollectionPage",
            "@id": self.url + "#page",
            "headline": plain(d["h1"]),
            "description": d["description"],
            "url": self.url,
            "image": SITE + "/assets/og-image.png",
            "inLanguage": "en",
            "datePublished": d["published"],
            "dateModified": d["updated"],
            "about": {"@id": SITE + "/#app"},
            "author": {"@type": "Organization", "name": "MacEx", "url": SITE + "/"},
            "publisher": {"@type": "Organization", "name": "MacEx", "url": SITE + "/",
                          "logo": {"@type": "ImageObject", "url": SITE + "/assets/icon-512.png"}},
        }]
        if self.slug == "index":
            graph.append({
                "@type": "ItemList",
                "name": "MacEx comparisons",
                "itemListElement": [
                    {"@type": "ListItem", "position": i, "url": SITE + c["href"], "name": plain(c["title"])}
                    for i, c in enumerate(next(x for x in d["sections"] if x["id"] == "comparisons")["cards"], 1)
                ],
            })
        graph.append({
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": i, "name": name, "item": url}
                for i, (name, url) in enumerate(crumbs, 1)
            ],
        })
        graph.append({
            "@type": "FAQPage",
            "mainEntity": [
                {"@type": "Question", "name": plain(f["q"]),
                 "acceptedAnswer": {"@type": "Answer", "text": plain(f["a"])}}
                for f in d["faq"]
            ],
        })
        body = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=2)
        return "\n".join("  " + line for line in body.splitlines())

    def head(self):
        d, p = self.d, self.prefix
        og_title = d.get("og_title", d["title"])
        return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>{escape(d['title'], quote=False)}</title>
  <meta name="description" content="{escape(d['description'])}">
  <meta name="theme-color" content="#f7f9fc">
  <link rel="canonical" href="{self.url}">
  <meta property="og:site_name" content="MacEx">
  <meta property="og:url" content="{self.url}">
  <meta property="og:title" content="{escape(og_title)}">
  <meta name="twitter:title" content="{escape(og_title)}">
  <meta name="twitter:description" content="{escape(d['description'])}">
  <meta property="og:description" content="{escape(d['description'])}">
  <meta property="og:type" content="{'website' if self.slug == 'index' else 'article'}">
  <meta property="og:image" content="{SITE}/assets/og-image.png">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="{SITE}/assets/og-image.png">
  <link rel="icon" href="{p}assets/mascot.svg" type="image/svg+xml">
  <link rel="apple-touch-icon" href="{p}assets/apple-touch-icon.png">
  <link rel="manifest" href="{p}site.webmanifest">
  <script type="application/ld+json">
{self.jsonld()}
  </script>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,400;9..40,500;9..40,600;9..40,700&family=Instrument+Serif:ital@0;1&family=Manrope:wght@600;700;800&display=swap">
  <link rel="stylesheet" href="{p}style.css?v={CSS_VERSION['style']}">
  <link rel="stylesheet" href="{p}docs/docs.css?v={CSS_VERSION['docs']}">
  <script src="{p}config.js" defer></script>
  <link rel="stylesheet" href="{p}article.css?v={CSS_VERSION['article']}">
  <script defer src="https://analytics.hemeshgupta.com/script.js" data-website-id="39604b49-3ffd-480a-bede-91caf13c1414"></script>
</head>"""

    # ---- body -------------------------------------------------------------
    def table(self, spec, cls):
        cols = "".join(f'<th scope="col">{self.html(c)}</th>' for c in spec["columns"])
        rows = []
        for row in spec["rows"]:
            cells = []
            for cell in row[1:]:
                if isinstance(cell, dict):
                    tag = cell.get("tag")
                    badge = f'<span class="tag {tag}">{TAGS[tag]}</span>' if tag else ""
                    cells.append(f"<td>{badge}{self.html(cell.get('text', ''))}</td>")
                else:
                    cells.append(f"<td>{self.html(cell)}</td>")
            klass = ' class="us"' if spec.get("highlight") and plain(row[0]).startswith(spec["highlight"]) else ""
            rows.append(f'        <tr{klass}><th scope="row">{self.html(row[0])}</th>{"".join(cells)}</tr>')
        note = f'\n  <p class="note">{self.html(spec["note"])}</p>' if spec.get("note") else ""
        return f"""  <div class="tbl-wrap">
    <table class="vs {cls}">
      <thead><tr><th scope="col">{self.html(spec.get('corner', ''))}</th>{cols}</tr></thead>
      <tbody>
{chr(10).join(rows)}
      </tbody>
    </table>
  </div>{note}"""

    def cta_row(self):
        p = self.prefix
        return (f'<div class="row-cta"><a class="button" href="{p}#pricing" data-buy>Get MacEx</a>'
                f'<a class="button ghost" href="{p}#mac-stage">Try the live demo <svg class="ico" aria-hidden="true"><use href="#i-arrow"/></svg></a></div>')

    def body(self):
        d, p = self.d, self.prefix
        out = []
        crumb = f'<a href="{p}">MacEx</a> › '
        if self.slug != "index":
            crumb += '<a href="../">Compare</a> › '
        crumb += escape(d["crumb"])
        out.append(f'  <nav class="crumbs-nav" aria-label="Breadcrumb">{crumb}</nav>')
        out.append(f'  <h1>{self.html(d["h1"])}</h1>')
        checked = f' {self.html(d["checked"])}' if d.get("checked") else ""
        out.append(f'  <p class="updated">Updated <time datetime="{d["updated"]}">{fmt_date(d["updated"])}</time>.{checked}</p>')
        out.append(f'\n  <div class="answer"><b>Short answer:</b> {self.html(d["answer"])}\n    {self.cta_row()}\n  </div>')

        short = {"at-a-glance": "At a glance", "features": "Features", "where-they-win": "Where it’s stronger",
                 "where-macex-wins": "Where MacEx is stronger", "price": "Price", "switching": "Switching"}
        toc = [(s["id"], s.get("toc") or (plain(s["heading"]) if len(plain(s["heading"])) <= 34 else short.get(s["id"], plain(s["heading"]))))
               for s in d["sections"]]
        toc += [("verdict", "Verdict"), ("faq", "FAQ")]
        out.append('\n  <nav class="toc" aria-label="On this page">\n    <ul>\n'
                   + "\n".join(f'      <li><a href="#{i}">{escape(t)}</a></li>' for i, t in toc)
                   + "\n    </ul>\n  </nav>")

        for s in d["sections"]:
            out.append(f'\n  <h2 id="{s["id"]}">{self.html(s["heading"])}</h2>')
            if s.get("intro"):
                out.append(f'  <p>{self.html(s["intro"])}</p>')
            if s.get("table"):
                out.append(self.table(s["table"], s["table"].get("class", "vs-glance")))
            if s.get("cards"):
                items = "\n".join(
                    f'    <li><a href="{p}{c["href"].lstrip("/")}">{self.html(c["title"])}<small>{self.html(c["small"])}</small></a></li>'
                    for c in s["cards"])
                out.append(f'  <ul class="hub-grid">\n{items}\n  </ul>')
            for block in s.get("html", []):
                out.append("  " + self.html(block))

        out.append(f'\n  <h2 id="verdict">{self.html(d["verdict"]["heading"])}</h2>')
        items = "\n".join(f"      <li>{self.html(v)}</li>" for v in d["verdict"]["items"])
        out.append(f'  <div class="verdict-box">\n    <ul>\n{items}\n    </ul>\n    {self.cta_row()}\n  </div>')

        out.append('\n  <h2 id="faq">Frequently asked questions</h2>\n  <div class="faq-list">')
        for f in d["faq"]:
            out.append(f'    <h3>{escape(plain(f["q"]))}</h3>\n    <p>{self.html(f["a"])}</p>')
        out.append("  </div>")

        if d.get("sources"):
            out.append('\n  <h2 id="sources">Sources</h2>')
            out.append(f'  <p class="note">{self.html(d.get("sources_note", "Checked on the date above. Prices are list prices in US dollars for one user."))}</p>')
            out.append('  <ul class="sources">\n' + "\n".join(
                f'    <li><a href="{escape(s["url"])}" rel="noopener">{escape(s["title"])}</a></li>' for s in d["sources"]) + "\n  </ul>")

        out.append('\n  <h2 id="related">Related</h2>\n  <ul class="related-links">')
        for r in d["related"]:
            out.append(f'    <li><a href="{p}{r["href"].lstrip("/")}">{self.html(r["title"])}<small>{self.html(r["small"])}</small></a></li>')
        out.append("  </ul>")

        out.append(f"""
  <div class="cta">
    <p>MacEx runs on macOS 14 or later, Apple silicon and Intel. One-time purchase, no account.</p>
    <div class="row">
      <a class="button" href="{p}#pricing" data-buy>Get MacEx · $9.99</a>
      <a class="button ghost" href="{p}#mac-stage">Try the live demo <svg class="ico" aria-hidden="true"><use href="#i-arrow"/></svg></a>
    </div>
  </div>""")
        return "\n".join(out)

    def render(self):
        p = self.prefix
        return f"""{self.head()}
<body>
{GENERATED.format(slug=self.slug)}
<a class="skip" href="#main">Skip to content</a>
<svg width="0" height="0" style="position:absolute" aria-hidden="true">
  <defs>
    <symbol id="i-arrow" viewBox="0 0 24 24"><path d="M7 17 17 7M8.5 7H17v8.5"/></symbol>
  </defs>
</svg>

<header class="docs-bar">
  <div class="docs-bar-in">
    <a class="brand" href="{p}" aria-label="MacEx home"><img src="{p}assets/mascot.svg" alt="" width="32" height="32">MacEx</a>
    <a class="site-link" style="margin-left:auto" href="{p}features/">Features</a>
    <a class="site-link" href="{'./' if self.slug == 'index' else '../'}">Compare</a>
    <a class="site-link" href="{p}docs/">Docs</a>
    <a class="button small" href="{p}#pricing">Get MacEx</a>
  </div>
</header>

<main id="main" class="container cmp">
{self.body()}
</main>

<footer class="docs-foot"><div><span>MacEx. Your Mac, explored.</span><span><a href="{p}">MacEx home</a> · <a href="{'./' if self.slug == 'index' else '../'}">All comparisons</a> · <a href="{p}docs/">Docs</a> · <a href="{p}#pricing">Pricing</a></span></div></footer>
</body>
</html>
"""


def validate(d, name):
    """The parts of COMPARE-SPEC.md that the content itself must satisfy."""
    problems = []
    need = ["slug", "title", "description", "h1", "crumb", "published", "updated", "answer", "sections", "verdict", "faq", "related"]
    problems += [f"missing {k}" for k in need if k not in d]
    if problems:
        return [f"{name}: {p}" for p in problems]
    if len(d["faq"]) < 6:
        problems.append(f"has {len(d['faq'])} FAQs; the spec needs at least 6")
    if len(d["related"]) < 8:
        problems.append(f"has {len(d['related'])} related links; the spec needs at least 8")
    if len(d["verdict"]["items"]) < 2:
        problems.append("verdict needs at least two 'choose X if' lines")
    ids = [s["id"] for s in d["sections"]]
    required = {"index": ["choose", "data", "comparisons"]}.get(d["slug"], ["at-a-glance", "features", "where-they-win", "where-macex-wins", "price", "switching"])
    problems += [f"missing section id {r!r}" for r in required if r not in ids]
    if d["slug"] != "index" and not d.get("sources"):
        problems.append("a comparison page must cite sources")
    if not 30 <= len(d["title"]) <= 65:
        problems.append(f"title is {len(d['title'])} characters; keep 30-65")
    if not 120 <= len(d["description"]) <= 165:
        problems.append(f"description is {len(d['description'])} characters; keep 120-165")
    for f in d["faq"]:
        if not plain(f["q"]).endswith("?"):
            problems.append(f"FAQ {f['q']!r} is not a question")
    date.fromisoformat(d["published"]), date.fromisoformat(d["updated"])
    return [f"{name}: {p}" for p in problems]


def build(check=False):
    problems, stale = [], []
    for source in sorted(CONTENT.glob("*.json")):
        data = json.loads(source.read_text(encoding="utf-8"))
        problems += validate(data, source.name)
        page = Page(data)
        target = ROOT / page.path.strip("/") / "index.html"
        html = page.render()
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != html:
                stale.append(target.relative_to(ROOT).as_posix())
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(html, encoding="utf-8")
    for p in problems:
        print("error:", p)
    for s in stale:
        print(f"error: {s} is stale; run python3 -B scripts/build_compare.py")
    if not problems and not stale:
        print("Comparison pages " + ("up to date." if check else "built."))
    return 1 if problems or stale else 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    sys.exit(build(parser.parse_args().check))
